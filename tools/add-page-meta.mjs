/* add-page-meta.mjs - M7: give every page a favicon, a canonical URL, and
   Open Graph / Twitter card tags, plus a description where one was missing.

   Idempotent: re-running replaces the managed block rather than stacking copies.
   The block is delimited by the M7 META comment markers.

   NOTE on the dynamic pages (project.html / post.html / role.html): this is a
   static host with no prerendering, and crawlers don't run our JS, so their OG
   tags are necessarily generic site-level defaults. The page <title> is still
   set per project/post at runtime for people in a browser.

   Run from tools/:  node add-page-meta.mjs */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://benbeary.github.io';
const OG_IMAGE = SITE + '/images/og-image.jpg';
const START = '    <!-- M7 META start (generated by tools/add-page-meta.mjs) -->';
const END = '    <!-- M7 META end -->';

const PAGES = {
    'index.html': {
        url: '/', type: 'website',
        title: 'Ben Beary | Game Developer',
        desc: 'Ben Beary, indie game developer, level designer, technical artist, and gameplay programmer. Browse featured projects and dev blogs.'
    },
    'about.html': {
        url: '/about.html', type: 'profile',
        title: 'About | Ben Beary',
        desc: 'Ben Beary, indie game developer, level designer, technical artist, and gameplay programmer.'
    },
    'projects.html': {
        url: '/projects.html', type: 'website',
        title: 'Projects | Ben Beary',
        desc: 'Game projects by Ben Beary, filter by skill or collection.'
    },
    'project.html': {
        url: '/project.html', type: 'article',
        title: 'Project | Ben Beary',
        desc: 'A project by Ben Beary: screenshots, clips, contributions, and dev blog posts.'
    },
    'post.html': {
        url: '/post.html', type: 'article',
        title: 'Post | Ben Beary',
        desc: 'A dev blog post by Ben Beary.'
    },
    'role.html': {
        url: '/role.html', type: 'profile',
        title: 'Ben Beary',
        desc: 'Selected work by Ben Beary, tailored to a specific role.'
    },
    '404.html': {
        url: '/404.html', type: 'website',
        title: 'Page not found | Ben Beary',
        desc: 'That page does not exist. Head back to Ben Beary\'s portfolio.'
    }
};

const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function block(cfg) {
    return [
        START,
        `    <link rel="canonical" href="${SITE}${cfg.url}">`,
        // Root-absolute: 404.html is served for URLs at any depth, so relative
        // icon paths would resolve against the missing directory.
        '    <link rel="icon" type="image/svg+xml" href="/favicon.svg">',
        '    <link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png">',
        '    <link rel="apple-touch-icon" href="/favicon-180.png">',
        '    <meta name="theme-color" content="#0b0e19">',
        `    <meta property="og:type" content="${cfg.type}">`,
        '    <meta property="og:site_name" content="Ben Beary">',
        `    <meta property="og:title" content="${esc(cfg.title)}">`,
        `    <meta property="og:description" content="${esc(cfg.desc)}">`,
        `    <meta property="og:url" content="${SITE}${cfg.url}">`,
        `    <meta property="og:image" content="${OG_IMAGE}">`,
        '    <meta property="og:image:width" content="1200">',
        '    <meta property="og:image:height" content="630">',
        '    <meta name="twitter:card" content="summary_large_image">',
        `    <meta name="twitter:title" content="${esc(cfg.title)}">`,
        `    <meta name="twitter:description" content="${esc(cfg.desc)}">`,
        `    <meta name="twitter:image" content="${OG_IMAGE}">`,
        END
    ].join('\n');
}

for (const [file, cfg] of Object.entries(PAGES)) {
    const full = path.join(REPO, file);
    let html;
    try { html = await fs.readFile(full, 'utf8'); }
    catch { console.log(`${file.padEnd(16)} (missing, skipped)`); continue; }

    // Drop any previous generated block so this stays idempotent.
    html = html.replace(new RegExp(START.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?', 'g'), '');

    // Ensure a description exists (some pages had none).
    if (!/name="description"/.test(html)) {
        html = html.replace(/(<title>[\s\S]*?<\/title>\n)/, `$1    <meta name="description" content="${esc(cfg.desc)}">\n`);
    }
    // Insert the block just before the first stylesheet link.
    html = html.replace(/(\n\s*<link rel="stylesheet")/, '\n' + block(cfg) + '$1');
    await fs.writeFile(full, html, 'utf8');
    console.log(`${file.padEnd(16)} meta injected`);
}
